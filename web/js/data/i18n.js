App.SUPPORTED_LOCALES = SUPPORTED_LOCALES
App.LOCALE_LABELS = LOCALE_LABELS
App.LOCALE_INTL = LOCALE_INTL
App.t = t
App.tCount = tCount
App.setLocale = setLocale
