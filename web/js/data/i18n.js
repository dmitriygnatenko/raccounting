function pluralIndex(locale, n) {
  const abs = Math.abs(n)
  if (locale === 'ru') {
    const mod10 = abs % 10
    const mod100 = abs % 100
    if (mod10 === 1 && mod100 !== 11) return 0
    if (mod10 >= 2 && mod10 <= 4 && !(mod100 >= 12 && mod100 <= 14)) return 1
    return 2
  }
  return abs === 1 ? 0 : 1
}

function detectBrowserLocale() {
  const langs = navigator.languages || [navigator.language || 'ru']
  for (const l of langs) {
    const code = (l || '').slice(0, 2).toLowerCase()
    if (SUPPORTED_LOCALES.includes(code)) return code
  }
  return 'ru'
}

function getStoredLocale() {
  try {
    const v = localStorage.getItem(STORAGE_KEY)
    return SUPPORTED_LOCALES.includes(v) ? v : null
  } catch {
    return null
  }
}

function setStoredLocale(locale) {
  try {
    localStorage.setItem(STORAGE_KEY, locale)
  } catch {}
}

function translate(locale, text, params) {
  const table = TRANSLATIONS[locale]
  let s = table ? (table[text] ?? text) : text
  if (params) {
    for (const k of Object.keys(params)) {
      s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), params[k])
    }
  }
  return s
}

const i18nStore = reactive({ locale: getStoredLocale() || detectBrowserLocale() })

function t(text, params) {
  return translate(i18nStore.locale, text, params)
}

function tCount(n, formsKey) {
  const forms = PLURAL_FORMS[formsKey]
  const locale = i18nStore.locale
  const arr = (forms && forms[locale]) || (forms && forms.ru) || []
  const idx = Math.min(pluralIndex(locale, n), arr.length - 1)
  return `${n} ${arr[idx] ?? ''}`
}

function setLocale(locale) {
  if (!SUPPORTED_LOCALES.includes(locale)) return
  i18nStore.locale = locale
  setStoredLocale(locale)
  document.documentElement.lang = locale
}

document.documentElement.lang = i18nStore.locale

